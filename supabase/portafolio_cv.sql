-- 4) GUARDADO ATÓMICO DEL CV COMPLETO -------------------------------------------
-- Recibe el perfil y las listas completas; reemplaza el contenido en una sola
-- transacción (si algo falla, no se guarda nada). El orden de cada lista define
-- la columna "orden".

create or replace function public.cv_guardar(
  p_perfil        jsonb,
  p_conocimientos jsonb,
  p_educacion     jsonb,
  p_proyectos     jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.cv_puede_editar() then
    raise exception 'No tienes permiso para editar el portafolio.' using errcode = '42501';
  end if;

  -- Perfil (fila única)
  insert into public.cv_perfil as perfil (
    id, nombre_completo, nombre_corto, titulo, roles, resumen, sobre_mi, foto_url,
    disponible, disponibilidad_texto, correo, anios_experiencia,
    contacto, idiomas, lenguajes, habilidades, redes, empresas, updated_at
  ) values (
    1,
    p_perfil ->> 'nombre_completo',
    p_perfil ->> 'nombre_corto',
    p_perfil ->> 'titulo',
    array(select jsonb_array_elements_text(coalesce(p_perfil -> 'roles', '[]'::jsonb))),
    p_perfil ->> 'resumen',
    array(select jsonb_array_elements_text(coalesce(p_perfil -> 'sobre_mi', '[]'::jsonb))),
    p_perfil ->> 'foto_url',
    coalesce((p_perfil ->> 'disponible')::boolean, true),
    coalesce(p_perfil ->> 'disponibilidad_texto', ''),
    p_perfil ->> 'correo',
    coalesce((p_perfil ->> 'anios_experiencia')::integer, 0),
    coalesce(p_perfil -> 'contacto', '[]'::jsonb),
    coalesce(p_perfil -> 'idiomas', '[]'::jsonb),
    coalesce(p_perfil -> 'lenguajes', '[]'::jsonb),
    array(select jsonb_array_elements_text(coalesce(p_perfil -> 'habilidades', '[]'::jsonb))),
    coalesce(p_perfil -> 'redes', '[]'::jsonb),
    array(select jsonb_array_elements_text(coalesce(p_perfil -> 'empresas', '[]'::jsonb))),
    now()
  )
  on conflict (id) do update set
    nombre_completo      = excluded.nombre_completo,
    nombre_corto         = excluded.nombre_corto,
    titulo               = excluded.titulo,
    roles                = excluded.roles,
    resumen              = excluded.resumen,
    sobre_mi             = excluded.sobre_mi,
    foto_url             = excluded.foto_url,
    disponible           = excluded.disponible,
    disponibilidad_texto = excluded.disponibilidad_texto,
    correo               = excluded.correo,
    anios_experiencia    = excluded.anios_experiencia,
    contacto             = excluded.contacto,
    idiomas              = excluded.idiomas,
    lenguajes            = excluded.lenguajes,
    habilidades          = excluded.habilidades,
    redes                = excluded.redes,
    empresas             = excluded.empresas,
    updated_at           = now();

  -- Conocimientos
  delete from public.cv_conocimientos where true;
  insert into public.cv_conocimientos (titulo, descripcion, icono, orden, visible)
  select e ->> 'titulo',
         e ->> 'descripcion',
         coalesce(nullif(e ->> 'icono', ''), 'sparkles'),
         n::integer,
         coalesce((e ->> 'visible')::boolean, true)
  from jsonb_array_elements(coalesce(p_conocimientos, '[]'::jsonb)) with ordinality as t(e, n);

  -- Educación
  delete from public.cv_educacion where true;
  insert into public.cv_educacion (institucion, titulo, estado, periodo, descripcion, orden, visible)
  select e ->> 'institucion',
         e ->> 'titulo',
         coalesce(e ->> 'estado', ''),
         coalesce(e ->> 'periodo', ''),
         coalesce(e ->> 'descripcion', ''),
         n::integer,
         coalesce((e ->> 'visible')::boolean, true)
  from jsonb_array_elements(coalesce(p_educacion, '[]'::jsonb)) with ordinality as t(e, n);

  -- Proyectos
  delete from public.cv_proyectos where true;
  insert into public.cv_proyectos
    (slug, titulo, resumen, descripcion, imagen_url, tecnologias, logros, repo_url, demo_url, nota_privada, orden, visible)
  select e ->> 'slug',
         e ->> 'titulo',
         e ->> 'resumen',
         coalesce(e ->> 'descripcion', ''),
         e ->> 'imagen_url',
         array(select jsonb_array_elements_text(coalesce(e -> 'tecnologias', '[]'::jsonb))),
         array(select jsonb_array_elements_text(coalesce(e -> 'logros', '[]'::jsonb))),
         nullif(e ->> 'repo_url', ''),
         nullif(e ->> 'demo_url', ''),
         nullif(e ->> 'nota_privada', ''),
         n::integer,
         coalesce((e ->> 'visible')::boolean, true)
  from jsonb_array_elements(coalesce(p_proyectos, '[]'::jsonb)) with ordinality as t(e, n);
end;
$$;

revoke all on function public.cv_guardar(jsonb, jsonb, jsonb, jsonb) from public, anon;
grant execute on function public.cv_guardar(jsonb, jsonb, jsonb, jsonb) to authenticated;


-- 5) STORAGE: bucket público "portafolio" para la foto y las imágenes -----------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('portafolio', 'portafolio', true, 5242880, array['image/jpeg', 'image/png', 'image/webp', 'image/gif', 'image/avif'])
on conflict (id) do update set
  public = true,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "portafolio: editores leen" on storage.objects;
create policy "portafolio: editores leen"
  on storage.objects for select
  to authenticated
  using (bucket_id = 'portafolio' and public.cv_puede_editar());

drop policy if exists "portafolio: editores suben" on storage.objects;
create policy "portafolio: editores suben"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'portafolio' and public.cv_puede_editar());

drop policy if exists "portafolio: editores actualizan" on storage.objects;
create policy "portafolio: editores actualizan"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'portafolio' and public.cv_puede_editar())
  with check (bucket_id = 'portafolio' and public.cv_puede_editar());

drop policy if exists "portafolio: editores borran" on storage.objects;
create policy "portafolio: editores borran"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'portafolio' and public.cv_puede_editar());


