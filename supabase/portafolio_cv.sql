-- =============================================================================
--  PORTAFOLIO / HOJA DE VIDA — Contenido administrable desde Supabase
-- =============================================================================
--  Ejecuta este script completo en Supabase → SQL Editor → New query → Run.
--  Es idempotente: se puede ejecutar varias veces (también sobre la versión
--  anterior del script) sin duplicar ni borrar datos.
--
--  Qué hace:
--   1. Crea las tablas cv_perfil, cv_conocimientos, cv_educacion y cv_proyectos
--      (prefijo cv_: no toca otras tablas que tenga el proyecto de Supabase).
--   2. Define quién puede editar: los correos de la tabla cv_editores
--      (función public.cv_puede_editar()). Revisa la sección 2.
--   3. RLS: los visitantes solo LEEN (filas visibles); los editores ven todo.
--   4. Función public.cv_guardar(): guarda el CV completo en una sola transacción
--      (la usa el editor /portafolio/editar).
--   5. Bucket público "portafolio" en Storage para la foto y las imágenes.
--   6. Carga el contenido inicial (el mismo de data/cv.ts) si las tablas están vacías.
--
--  Edición: botón «Editar» del sitio (/portafolio/editar) con una cuenta de
--  Supabase Auth cuyo correo esté en cv_editores. También puedes editar desde
--  Table Editor; el sitio se actualiza en ~1 minuto.
-- =============================================================================


