-- 2) QUIÉN PUEDE EDITAR ---------------------------------------------------------
-- Solo los correos de la tabla cv_editores pueden usar el editor. Para autorizar
-- tu cuenta (la misma con la que inicias sesión en /login), ejecuta:
--   insert into public.cv_editores (email) values ('tu-correo@ejemplo.com');
-- Para quitar a alguien:
--   delete from public.cv_editores where email = 'correo@ejemplo.com';

create table if not exists public.cv_editores (
  email      text        primary key check (email = lower(email)),
  created_at timestamptz not null default now()
);

comment on table public.cv_editores is 'Portafolio: correos (en minúsculas) autorizados para usar el editor /portafolio/editar.';

-- Sin políticas: nadie la lee ni la cambia desde la API; solo la consulta cv_puede_editar().
alter table public.cv_editores enable row level security;

-- Solo la primera vez (tabla vacía): si el proyecto de Supabase ya tiene una tabla
-- public.usuarios con administradores (por ejemplo, de otra aplicación que comparte
-- la base de datos), se autorizan sus correos. Si no existe, no pasa nada.
do $$
begin
  if not exists (select 1 from public.cv_editores) and to_regclass('public.usuarios') is not null then
    execute $q$
      insert into public.cv_editores (email)
      select distinct lower(email)
      from public.usuarios
      where rol = 'admin' and activo is not false and email is not null
      on conflict do nothing
    $q$;
  end if;
exception when others then
  raise notice 'No se copiaron correos desde public.usuarios: %', sqlerrm;
end;
$$;

create or replace function public.cv_puede_editar()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.cv_editores e
    where e.email = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

revoke all on function public.cv_puede_editar() from public, anon;
grant execute on function public.cv_puede_editar() to authenticated;


